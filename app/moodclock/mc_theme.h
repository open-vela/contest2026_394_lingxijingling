// ============================================================================
//  theme.h —— 四套随时间自动切换的温和配色
//
//  设计原则：低饱和、相邻色相之间过渡柔和，避免纯白纯黑。
//  夜里那套是深底浅字（视觉上"关灯"了，不刺眼），白天那套是浅底深字。
// ============================================================================
#pragma once
#include <stdint.h>

#define TH_RGB(r, g, b) ((uint16_t)((((uint16_t)(r) & 0xF8) << 8) | \
                                    (((uint16_t)(g) & 0xFC) << 3) | \
                                    (((uint16_t)(b) & 0xF8) >> 3)))

struct Theme {
  const char* name;
  uint16_t bgTop;     // 背景渐变上端
  uint16_t bgBot;     // 背景渐变下端
  uint16_t text;      // 主文字（时间）
  uint16_t sub;       // 次要文字（日期、标签）
  uint16_t accent;    // 强调色（分隔线、点缀）
  uint16_t icon;      // 心情图标主体
  uint16_t iconSoft;  // 心情图标辅色（云朵、余晖）
  bool     dark;      // 深底浅字
};

// 0 晨光 / 1 晴昼 / 2 暮色 / 3 夜幕
