static inline int themeIndexForHour(int h) {
  if (h >=  5 && h <  8) return 0;   // 晨光
  if (h >=  8 && h < 17) return 1;   // 晴昼
  if (h >= 17 && h < 20) return 2;   // 暮色
  return 3;                          // 夜幕
}
